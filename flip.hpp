// ============================================================
// 8bitライン取り出し
// ============================================================

// 横方向
inline uint8_t join_h_line(uint64_t x, int t)
{
    return (x >> (HW * t)) & 0xFFU;
}


// 縦方向
inline uint8_t join_v_line(uint64_t x, int c)
{
    x =
        (x >> c)
        &
        0b0000000100000001000000010000000100000001000000010000000100000001ULL;

    return
        (
            x *
            0b0000000100000010000001000000100000010000001000000100000010000000ULL
        ) >> 56;
}


// d7方向
inline uint8_t join_d7_line(uint64_t x, int t)
{
    x =
        (x >> t)
        &
        0b0000000000000010000001000000100000010000001000000100000010000001ULL;

    return
        (
            x *
            0b1000000010000000100000001000000010000000100000001000000010000000ULL
        ) >> 56;
}


// d9方向
inline uint8_t join_d9_line(uint64_t x, int t)
{
    if (t > 0)
        x >>= t;
    else if (t < 0)
        x <<= (-t);

    x &=
        0b1000000001000000001000000001000000001000000001000000001000000001ULL;

    return
        (
            x *
            0b0000000100000001000000010000000100000001000000010000000100000001ULL
        ) >> 56;
}


// ============================================================
// 8bit → 64bit 展開
// ============================================================

inline uint64_t split_v_line(uint8_t x, int c)
{
    uint64_t res = 0;

    uint64_t a = x & 0b00001111;
    uint64_t b = x & 0b11110000;

    res = a | (b << 28);

    a =
        res &
        0b0000000000000000000000000000001100000000000000000000000000000011ULL;

    b =
        res &
        0b0000000000000000000000000000110000000000000000000000000000001100ULL;

    res = a | (b << 14);

    a =
        res &
        0b0000000000000001000000000000000100000000000000010000000000000001ULL;

    b =
        res &
        0b0000000000000010000000000000001000000000000000100000000000000010ULL;

    res = a | (b << 7);

    return res << c;
}


inline uint64_t split_d7_line(uint8_t x, int t)
{
    // 8bitの順序を反転
    uint8_t c = x & 0b01010101;
    uint8_t d = x & 0b10101010;

    x = (c << 1) | (d >> 1);

    c = x & 0b00110011;
    d = x & 0b11001100;

    x = (c << 2) | (d >> 2);

    c = x & 0b00001111;
    d = x & 0b11110000;

    x = (c << 4) | (d >> 4);


    uint64_t a = x & 0b00001111;
    uint64_t b = x & 0b11110000;

    uint64_t res = a | (b << 24);

    a =
        res &
        0b0000000000000000000000000000000000110000000000000000000000000011ULL;

    b =
        res &
        0b0000000000000000000000000000000011000000000000000000000000001100ULL;

    res = a | (b << 12);

    a =
        res &
        0b0000000100000000000001000000000000010000000000000100000000000001ULL;

    b =
        res &
        0b0000001000000000000010000000000000100000000000001000000000000010ULL;

    res = a | (b << 6);

    return res << t;
}


inline uint64_t split_d9_line(uint8_t x, int t)
{
    uint64_t a = x & 0b00001111;
    uint64_t b = x & 0b11110000;

    uint64_t res = a | (b << 32);

    a =
        res &
        0b0000000000000000000000000011000000000000000000000000000000000011ULL;

    b =
        res &
        0b0000000000000000000000001100000000000000000000000000000000001100ULL;

    res = a | (b << 16);

    a =
        res &
        0b0000000001000000000000000001000000000000000001000000000000000001ULL;

    b =
        res &
        0b0000000010000000000000000010000000000000000010000000000000000010ULL;

    res = a | (b << 8);

    if (t > 0)
        return res << t;

    return res >> (-t);
}


// ============================================================
// split前計算テーブル
// ============================================================

inline uint64_t split_v_lines[N_8BIT];

inline uint64_t split_d7_lines[N_8BIT][N_DIAG_LINE];

inline uint64_t split_d9_lines[N_8BIT][N_DIAG_LINE];


// ============================================================
// 反転位置前計算テーブル
// ============================================================
//
// [自分石8bit][相手石8bit][着手位置]
//           ↓
//      反転する8bit
//
// ============================================================

inline uint8_t flip_pre_calc[N_8BIT][N_8BIT][HW];


// ============================================================
// splitテーブル初期化
// ============================================================

inline void split_init()
{
    for (int i = 0; i < N_8BIT; ++i)
    {
        // 縦は0列目だけ作成
        // 実際の列へは後で << u する
        split_v_lines[i] =
            split_v_line(
                static_cast<uint8_t>(i),
                0
            );


        // 斜めはライン位置も含めて前計算
        for (int t = 0; t < N_DIAG_LINE; ++t)
        {
            split_d7_lines[i][t] =
                split_d7_line(
                    static_cast<uint8_t>(i),
                    t + 2
                );

            split_d9_lines[i][t] =
                split_d9_line(
                    static_cast<uint8_t>(i),
                    t - 5
                );
        }
    }
}


// ============================================================
// flip_pre_calc 初期化
// ============================================================

inline void flip_init()
{
    for (int player = 0; player < N_8BIT; ++player)
    {
        for (int opponent = 0; opponent < N_8BIT; ++opponent)
        {
            for (int place = 0; place < HW; ++place)
            {
                flip_pre_calc[player][opponent][place] = 0;


                // playerとopponentが重なっていたら無効
                if ((player & opponent) != 0)
                    continue;


                // 着手位置が空きでなければ無効
                if (
                    ((player >> place) & 1) ||
                    ((opponent >> place) & 1)
                )
                {
                    continue;
                }


                uint8_t put =
                    static_cast<uint8_t>(1U << place);


                // 端は挟めないため除く
                uint8_t opponent_inner =
                    static_cast<uint8_t>(
                        opponent & 0b01111110
                    );


                // ------------------------------------------------
                // bit番号が小さくなる方向
                // ------------------------------------------------

                uint8_t reversed = 0;
                uint8_t cursor =
                    static_cast<uint8_t>(put >> 1);


                while (cursor & opponent_inner)
                {
                    reversed |= cursor;
                    cursor >>= 1;
                }


                if (cursor & player)
                {
                    flip_pre_calc[player][opponent][place]
                        |= reversed;
                }


                // ------------------------------------------------
                // bit番号が大きくなる方向
                // ------------------------------------------------

                reversed = 0;
                cursor =
                    static_cast<uint8_t>(put << 1);


                while (cursor & opponent_inner)
                {
                    reversed |= cursor;
                    cursor <<= 1;
                }


                if (cursor & player)
                {
                    flip_pre_calc[player][opponent][place]
                        |= reversed;
                }
            }
        }
    }
}


// ============================================================
// 着手情報
// ============================================================

class Flip
{
public:

    uint_fast8_t pos;

    uint64_t flip;


    // --------------------------------------------------------
    // 指定したplaceに着手した場合に反転する石を計算
    // --------------------------------------------------------

    inline void calc_flip(
        uint64_t player,
        uint64_t opponent,
        uint_fast8_t place
    )
    {
        flip = 0;

        pos = place;


        const int t = place / HW;

        const int u = place % HW;


        uint8_t p;
        uint8_t o;


        // ====================================================
        // 横方向
        // ====================================================

        p =
            join_h_line(
                player,
                t
            );

        o =
            join_h_line(
                opponent,
                t
            );


        flip |=
            static_cast<uint64_t>(
                flip_pre_calc[p][o][u]
            )
            << (HW * t);


        // ====================================================
        // 縦方向
        // ====================================================

        p =
            join_v_line(
                player,
                u
            );

        o =
            join_v_line(
                opponent,
                u
            );


        flip |=
            split_v_lines[
                flip_pre_calc[p][o][t]
            ]
            << u;


        // ====================================================
        // d7斜め方向
        // ====================================================

        if (
            u + t >= 2 &&
            u + t <= 12
        )
        {
            p =
                join_d7_line(
                    player,
                    u + t
                )
                &
                d7_mask[place];


            o =
                join_d7_line(
                    opponent,
                    u + t
                )
                &
                d7_mask[place];


            uint8_t line_flip =
                flip_pre_calc
                [p]
                [o]
                [HW_M1 - t]
                &
                d7_mask[place];


            flip |=
                split_d7_lines
                [line_flip]
                [u + t - 2];
        }


        // ====================================================
        // d9斜め方向
        // ====================================================

        if (
            u - t >= -5 &&
            u - t <= 5
        )
        {
            p =
                join_d9_line(
                    player,
                    u - t
                )
                &
                d9_mask[place];


            o =
                join_d9_line(
                    opponent,
                    u - t
                )
                &
                d9_mask[place];


            uint8_t line_flip =
                flip_pre_calc
                [p]
                [o]
                [t]
                &
                d9_mask[place];


            flip |=
                split_d9_lines
                [line_flip]
                [u - t + 5];
        }
    }
};


// ============================================================
// move.hpp全体の初期化
// ============================================================

inline void move_init()
{
    split_init();

    flip_init();
}